import logging
import sys
import duckdb
from pathlib import Path
from rdflib import Graph, Namespace, RDF, RDFS, OWL, XSD, Literal

import logging_config
logging_config.setup()
log = logging.getLogger("hosp.ontology")

DB_FILE  = Path(__file__).parent / "hospitality.duckdb"
TTL_FILE = Path(__file__).parent.parent / "ontology" / "hospitality_ontology.ttl"

HOSP = Namespace("http://hospitality.example.org/ontology#")
INST = Namespace("http://hospitality.example.org/instance/")

SOURCE_TABLES = (
    "epos_transactions",
    "wfm_shifts",
    "procurement_products",
    "sap_sales",
    "hr_employees",
)


def introspect_schemas(db: duckdb.DuckDBPyConnection) -> dict:
    """Read DuckDB table schemas — mirrors COA SCAN reading from Glue Data Catalog."""
    log.info("Introspecting schemas from %d source tables", len(SOURCE_TABLES))
    schemas = {}
    for table in SOURCE_TABLES:
        cols      = db.execute(f"DESCRIBE {table}").fetchall()
        row_count = db.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        schemas[table] = {
            "columns":   [(c[0], c[1]) for c in cols],
            "row_count": row_count,
        }
        log.debug("Schema: %s — %d columns, %d rows", table, len(cols), row_count)
    return schemas


def build_class_hierarchy(g: Graph) -> None:
    classes = {
        "HospitalitySite": "A catering site (campus, office, hospital, etc.) operated by the Hospitality Group",
        "Employee":        "A workforce member — permanent, part-time, zero-hours, or agency",
        "Product":         "A food or beverage product sold at a site",
        "Transaction":     "A point-of-sale transaction recorded by the EPOS system (Oracle MICROS)",
        "Shift":           "A worked shift recorded by Infor WFM",
        "Supplier":        "A supplier in the Coupa national procurement catalogue",
        "SAPInvoice":      "A client invoice generated by SAP S/4HANA for catering services",
        "HRRecord":        "An employee HR & payroll record in SAP SuccessFactors",
    }
    for cls_name, comment in classes.items():
        cls_uri = HOSP[cls_name]
        g.add((cls_uri, RDF.type,     OWL.Class))
        g.add((cls_uri, RDFS.label,   Literal(cls_name)))
        g.add((cls_uri, RDFS.comment, Literal(comment)))


def build_properties(g: Graph) -> None:
    object_props = [
        ("hasTransaction", "HospitalitySite", "Transaction", "EPOS transactions at this site"),
        ("hasShift",       "HospitalitySite", "Shift",       "Infor WFM shifts worked at this site"),
        ("hasSAPInvoice",  "HospitalitySite", "SAPInvoice",  "SAP client invoices raised against this cost centre"),
        ("hasHRRecord",    "HospitalitySite", "HRRecord",    "SuccessFactors employee records in this org unit"),
        ("workedBy",       "Shift",           "Employee",    "Employee who worked this shift (WFM to SF identity gap)"),
        ("soldItem",       "Transaction",     "Product",     "Product sold in this EPOS transaction"),
        ("suppliedBy",     "Product",         "Supplier",    "Coupa supplier for this product"),
    ]
    for prop_name, domain, range_, comment in object_props:
        prop = HOSP[prop_name]
        g.add((prop, RDF.type,       OWL.ObjectProperty))
        g.add((prop, RDFS.domain,    HOSP[domain]))
        g.add((prop, RDFS.range,     HOSP[range_]))
        g.add((prop, RDFS.comment,   Literal(comment)))

    # Identity-bridging datatype properties
    # Each property captures one source system's ID format for the same site.
    id_props = [
        # Site identity bridges — four different formats for the same physical site
        ("eposSiteId",   "HospitalitySite", XSD.string,
         "site_id as recorded by Oracle MICROS EPOS (format: SITE-LDN-01)"),
        ("inforSiteCode","HospitalitySite", XSD.string,
         "site_id as recorded by Infor WFM (format: GBR_SITE_0001) — country-prefixed with underscore"),
        ("sapCostCenter","HospitalitySite", XSD.string,
         "cost_center_code as recorded by SAP S/4HANA (format: CC-GBR-001) — ERP cost centre"),
        ("sfOrgUnitId",  "HospitalitySite", XSD.string,
         "org_unit_id as recorded by SAP SuccessFactors (format: OU-GBR-001) — HR org unit"),
        ("siteName",     "HospitalitySite", XSD.string,
         "Human-readable site name"),
        # Product identity bridges — EPOS till code vs Coupa catalogue SKU
        ("eposItemId",          "Product", XSD.string,
         "Item code as used in Oracle MICROS EPOS (format: EPOS-LATTE)"),
        ("procProductId",       "Product", XSD.string,
         "Product SKU in the Coupa procurement catalogue (format: PROD-BEV-001)"),
        ("productName",         "Product", XSD.string,
         "Canonical product description"),
        ("category",            "Product", XSD.string,
         "Product category"),
        ("contractedPriceGBP",  "Product", XSD.decimal,
         "Coupa frame contract price per unit (GBP)"),
    ]
    for prop_name, domain, xsd_type, comment in id_props:
        prop = HOSP[prop_name]
        g.add((prop, RDF.type,      OWL.DatatypeProperty))
        g.add((prop, RDFS.domain,   HOSP[domain]))
        g.add((prop, RDFS.range,    xsd_type))
        g.add((prop, RDFS.comment,  Literal(comment)))


def add_individuals(g: Graph, db: duckdb.DuckDBPyConnection) -> None:
    # Sites — each canonical individual carries ALL four source-system IDs
    sites = [
        # canonical_id   epos_id       infor_code      sap_cc        sf_org       name
        ("gbr-lnd-01", "SITE-LDN-01", "GBR_SITE_0001","CC-GBR-001","OU-GBR-001","London Canary Wharf"),
        ("gbr-lnd-02", "SITE-LDN-02", "GBR_SITE_0002","CC-GBR-002","OU-GBR-002","London City"),
        ("gbr-man-01", "SITE-MAN-01", "GBR_SITE_0101","CC-GBR-101","OU-GBR-101","Manchester"),
    ]
    for canonical_id, epos_id, infor_code, sap_cc, sf_org, name in sites:
        site = INST[f"site/{canonical_id}"]
        g.add((site, RDF.type,             HOSP.HospitalitySite))
        g.add((site, RDFS.label,           Literal(name)))
        g.add((site, HOSP.siteName,        Literal(name)))
        g.add((site, HOSP.eposSiteId,      Literal(epos_id)))    # "SITE-LDN-01"
        g.add((site, HOSP.inforSiteCode,   Literal(infor_code))) # "GBR_SITE_0001"
        g.add((site, HOSP.sapCostCenter,   Literal(sap_cc)))     # "CC-GBR-001"
        g.add((site, HOSP.sfOrgUnitId,     Literal(sf_org)))     # "OU-GBR-001"

    # Products — EPOS item code bridged to Coupa catalogue SKU
    products = db.execute(
        "SELECT proc_product_id, epos_item_id, product_name, category, contracted_price_gbp "
        "FROM procurement_products"
    ).fetchall()
    for proc_id, epos_item_id, name, category, price in products:
        canonical_id = proc_id.lower().replace("-", "_")
        prod = INST[f"product/{canonical_id}"]
        g.add((prod, RDF.type,                HOSP.Product))
        g.add((prod, RDFS.label,              Literal(name)))
        g.add((prod, HOSP.productName,        Literal(name)))
        g.add((prod, HOSP.category,           Literal(category)))
        g.add((prod, HOSP.procProductId,      Literal(proc_id)))
        g.add((prod, HOSP.contractedPriceGBP, Literal(float(price), datatype=XSD.decimal)))
        if epos_item_id:
            g.add((prod, HOSP.eposItemId,     Literal(epos_item_id)))


def print_schema_summary(schemas: dict) -> None:
    print("Source system schemas (local equivalent of COA SCAN / Glue Crawler output):")
    print()
    for table, meta in schemas.items():
        print(f"  {table} ({meta['row_count']} rows)")
        for col_name, col_type in meta["columns"]:
            print(f"    {col_name:<35} {col_type}")
        print()


def main() -> None:
    if not DB_FILE.exists():
        log.error("DB not found at %s — run bootstrap_hospitality.py first", DB_FILE)
        print(f"ERROR: {DB_FILE} not found — run bootstrap_hospitality.py first.")
        sys.exit(1)

    show_sparql = "--show-sparql" in sys.argv
    log.info("Opening DB: %s", DB_FILE)
    db = duckdb.connect(str(DB_FILE), read_only=True)

    schemas = introspect_schemas(db)
    print_schema_summary(schemas)

    g = Graph()
    g.bind("hosp", HOSP)
    g.bind("inst", INST)
    g.bind("owl",  OWL)
    g.bind("rdfs", RDFS)
    g.bind("xsd",  XSD)

    log.info("Building OWL class hierarchy")
    build_class_hierarchy(g)
    log.info("Building OWL properties (object + datatype identity bridges)")
    build_properties(g)
    log.info("Adding OWL individuals (sites + products)")
    add_individuals(g, db)
    db.close()

    TTL_FILE.parent.mkdir(exist_ok=True)
    g.serialize(destination=str(TTL_FILE), format="turtle")

    n_classes  = len(list(g.subjects(RDF.type, OWL.Class)))
    n_obj      = len(list(g.subjects(RDF.type, OWL.ObjectProperty)))
    n_dt       = len(list(g.subjects(RDF.type, OWL.DatatypeProperty)))
    n_sites    = len(list(g.subjects(RDF.type, HOSP.HospitalitySite)))
    n_products = len(list(g.subjects(RDF.type, HOSP.Product)))

    log.info(
        "Ontology written: %s — classes=%d  obj_props=%d  dt_props=%d  "
        "sites=%d  products=%d  total_triples=%d",
        TTL_FILE, n_classes, n_obj, n_dt, n_sites, n_products, len(g),
    )
    print(f"Ontology written : {TTL_FILE}")
    print(f"  Classes        : {n_classes}")
    print(f"  Properties     : {n_obj + n_dt}  ({n_obj} object + {n_dt} datatype)")
    print(f"  Individuals    : {n_sites} sites + {n_products} products")
    print(f"  Total triples  : {len(g)}")
    print()
    print("Site identity bridges (4 systems → 1 canonical site individual):")
    print("  hosp:eposSiteId    'SITE-LDN-01'    ← Oracle MICROS EPOS")
    print("  hosp:inforSiteCode 'GBR_SITE_0001'  ← Infor WFM")
    print("  hosp:sapCostCenter 'CC-GBR-001'     ← SAP S/4HANA cost centre")
    print("  hosp:sfOrgUnitId   'OU-GBR-001'     ← SAP SuccessFactors org unit")

    if show_sparql:
        print()
        print("SPARQL — resolve EPOS site_id → all system IDs:")
        print("""
    PREFIX hosp: <http://hospitality.example.org/ontology#>
    SELECT ?epos_id ?infor_code ?sap_cc ?sf_org ?site_name WHERE {
        ?site hosp:eposSiteId    ?epos_id ;
              hosp:inforSiteCode ?infor_code ;
              hosp:sapCostCenter ?sap_cc ;
              hosp:sfOrgUnitId   ?sf_org ;
              hosp:siteName      ?site_name .
        FILTER(?epos_id = "SITE-LDN-01")
    }
    → infor_code="GBR_SITE_0001"  sap_cc="CC-GBR-001"
      sf_org="OU-GBR-001"         site_name="London Canary Wharf"
        """)


if __name__ == "__main__":
    main()
